package org.qw3rtrun.p3d.core;

import org.junit.jupiter.api.Test;
import reactor.core.publisher.Flux;
import reactor.test.StepVerifier;

import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.atomic.AtomicLong;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * A stored file as the blocks a printer should be sent.
 *
 * <p>Two things are asserted here and both have bitten this repository before: what a line actually
 * carries once the comments are off it, and that reading a file does not mean holding one.
 */
class GcodeLinesTest {

    private static ByteBuffer chunk(String text) {
        return ByteBuffer.wrap(text.getBytes(StandardCharsets.UTF_8));
    }

    @Test
    void aPlainCommandIsTheBlock() {
        assertEquals("G28", GcodeLines.blockOf("G28"));
        assertEquals("G1 X10 Y10 E1.5", GcodeLines.blockOf("G1 X10 Y10 E1.5"));
    }

    /**
     * A trailing comment is stripped, because the transport frames what it is given verbatim.
     *
     * <p>{@code GEncoder.frame} appends the checksum field behind whatever it was handed, and a
     * comment runs to end of line - so a block delivered with one on it arrives at the firmware
     * with its checksum inside the comment and is rejected.
     */
    @Test
    void aTrailingCommentIsStripped() {
        assertEquals("G1 X10", GcodeLines.blockOf("G1 X10 ; wipe the nozzle"));
        assertEquals("G1 X10", GcodeLines.blockOf("G1 X10 (a note)"));
    }

    /** A line that asks for nothing is dropped rather than spending a line number to say it. */
    @Test
    void commentsAndBlanksCarryNothing() {
        assertEquals("", GcodeLines.blockOf(";LAYER:1"));
        assertEquals("", GcodeLines.blockOf("; generated by PrusaSlicer"));
        assertEquals("", GcodeLines.blockOf("(a parenthesised note)"));
        assertEquals("", GcodeLines.blockOf(""));
        assertEquals("", GcodeLines.blockOf("   "));
    }

    /**
     * A {@code ;} inside a parenthesised comment does not start a new one.
     *
     * <p>Which is why {@code :gcode}'s reader does this and a split on {@code ;} does not.
     */
    @Test
    void aSemicolonInsideAnInlineCommentIsNotAComment() {
        assertEquals("G1 X10", GcodeLines.blockOf("G1 X10 (wipe ; then purge)"));
    }

    /**
     * A file that already carries numbering is fed without it.
     *
     * <p>The line counter belongs to the transport - a pre-numbered block would be framed in front
     * of its own {@code N} and desynchronise the session - so what is taken is the block's body,
     * which is defined as the slice between the number and the checksum.
     */
    @Test
    void aPreNumberedBlockIsFedAsItsBodyAlone() {
        assertEquals("G28", GcodeLines.blockOf("N1 G28*18"));
    }

    @Test
    void aFileIsReadAsItsCommands() {
        var file = """
                ;FLAVOR:Marlin
                ;TIME:3661

                G28 ; home
                G1 X10 Y10
                ;LAYER:0
                M104 S200
                """;

        StepVerifier.create(GcodeLines.blocksOf(Flux.just(chunk(file))))
                .expectNext("G28", "G1 X10 Y10", "M104 S200")
                .verifyComplete();
    }

    /** A chunk boundary is not a line boundary, and the framing must not care where it falls. */
    @Test
    void aLineSplitAcrossChunksIsRejoined() {
        StepVerifier.create(GcodeLines.blocksOf(
                        Flux.just(chunk("G1 X"), chunk("10\nG2"), chunk("8\nM104 S200\n"))))
                .expectNext("G1 X10", "G28", "M104 S200")
                .verifyComplete();
    }

    /** A file whose last line has no terminator still ends in a line. */
    @Test
    void aFileWithNoTrailingNewlineStillYieldsItsLastBlock() {
        StepVerifier.create(GcodeLines.blocksOf(Flux.just(chunk("G28\nM104 S200"))))
                .expectNext("G28", "M104 S200")
                .verifyComplete();
    }

    /** Windows line endings are not part of the block. */
    @Test
    void carriageReturnsAreNotPartOfTheBlock() {
        StepVerifier.create(GcodeLines.blocksOf(Flux.just(chunk("G28\r\nM104 S200\r\n"))))
                .expectNext("G28", "M104 S200")
                .verifyComplete();
    }

    /**
     * Reading a file does not mean holding one.
     *
     * <p>The same assertion plan item C1 makes of the store, and for the same reason: the obvious
     * shapes here - {@code collectList}, a {@code bufferUntil} over characters - would read a
     * two-hundred-megabyte file into the heap to hand out its first line. What is measured is the
     * largest single {@code request(n)} this makes of the file store.
     */
    @Test
    void itNeverAsksTheStoreForMoreThanOneChunk() {
        var largestRequest = new AtomicLong();
        var chunks = Flux.range(0, 2048)
                .map(i -> chunk("G1 X" + i + "\n"))
                .doOnRequest(n -> largestRequest.accumulateAndGet(n, Math::max));

        StepVerifier.create(GcodeLines.blocksOf(chunks).count())
                .expectNext(2048L)
                .verifyComplete();

        assertEquals(1, largestRequest.get(),
                "it asked the file store for " + largestRequest.get() + " chunks at once");
    }

    /** And a consumer that takes one block at a time gets one, rather than the file. */
    @Test
    void aSlowConsumerDrawsOneBlockAtATime() {
        var pulled = new AtomicLong();
        var chunks = Flux.range(0, 512)
                .map(i -> chunk("G1 X" + i + "\n"))
                .doOnRequest(n -> pulled.incrementAndGet());

        StepVerifier.create(GcodeLines.blocksOf(chunks), 1)
                .expectNext("G1 X0")
                .thenRequest(1)
                .expectNext("G1 X1")
                .thenCancel()
                .verify();

        assertTrue(pulled.get() < 10,
                "the store was asked " + pulled.get() + " times for two blocks");
    }
}
