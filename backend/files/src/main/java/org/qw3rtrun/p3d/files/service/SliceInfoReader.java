package org.qw3rtrun.p3d.files.service;

import org.qw3rtrun.p3d.api.files.SliceInfo;
import org.qw3rtrun.p3d.g.code.core.token.GComment;
import org.qw3rtrun.p3d.g.code.core.token.GTokenizer;

import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;

/**
 * What the slicer said, read out of the file's comments.
 *
 * <p><strong>The comments are found by {@code :gcode}'s tokenizer and not by a pattern of this
 * module's own.</strong> That is plan item C1's third done-when condition, and the reason for it is
 * that "a comment" is a surprisingly deep question: a {@code ;} inside a parenthesised comment does
 * not open a new one, a {@code (} inside a tail comment is text, and the tokenizer already answers
 * both against a corpus and a written spec. A second reader of G-code text in this repository is
 * exactly what {@code :backend:terminal} spent a change getting rid of.
 *
 * <p><strong>What is done here is the other half, and it is not parsing G-code.</strong> Once the
 * tokenizer has handed over the text of a comment, reading {@code TIME:3661} out of it is reading
 * one slicer's convention - and there is no standard for any of it. Cura writes
 * {@code ;TIME:3661}; PrusaSlicer writes {@code ; estimated printing time (normal mode) = 1h 2m 3s}.
 * Those are two programs' habits rather than anything the format says, so they are recorded as a
 * table here and nowhere near {@code :gcode}.
 *
 * <p>Everything is optional and a value that does not parse is simply not taken. A file from a
 * slicer nothing here has heard of yields {@link SliceInfo#unknown()}, which is a fact rather than
 * a failure: it is still a perfectly printable file.
 */
final class SliceInfoReader {

    private SliceInfoReader() {
    }

    /**
     * Reads what it can from one or more windows of a file.
     *
     * <p>Several windows because slicers disagree about where the summary goes - Cura puts it at
     * the top, PrusaSlicer repeats much of its configuration at the bottom - and because reading
     * the whole file would mean tokenizing every motion command in it to find four numbers. The
     * first value found for a field wins, so the head window takes precedence over the tail.
     */
    static SliceInfo read(byte[]... windows) {
        var found = new Found();
        for (byte[] window : windows) {
            var text = new String(window, StandardCharsets.UTF_8);
            var tokens = GTokenizer.INSTANCE.parse((CharSequence) text).iterator();
            while (tokens.hasNext()) {
                if (tokens.next() instanceof GComment comment) {
                    found.offer(comment.getString());
                }
            }
        }
        return found.toSliceInfo();
    }

    /** The first value seen for each field, because the head window is read before the tail. */
    private static final class Found {
        String slicer;
        Long estimatedSeconds;
        BigDecimal filamentMillimetres;
        BigDecimal layerHeight;

        void offer(String comment) {
            var text = comment.trim();
            var lower = text.toLowerCase();

            // The slicer names itself in prose rather than as a key-value, in both dialects.
            if (slicer == null && lower.startsWith("generated with ")) {
                slicer = text.substring("generated with ".length()).trim();
                return;
            }
            if (slicer == null && lower.startsWith("generated by ")) {
                slicer = firstTwoWords(text.substring("generated by ".length()).trim());
                return;
            }

            int split = separator(text);
            if (split < 0) {
                return;
            }
            var key = normalise(text.substring(0, split));
            var value = text.substring(split + 1).trim();
            if (value.isEmpty()) {
                return;
            }

            switch (key) {
                // Cura: ;TIME:3661 - already seconds.
                case "time" -> estimatedSeconds = orKeep(estimatedSeconds, wholeNumber(value));
                // PrusaSlicer: ; estimated printing time (normal mode) = 1h 2m 3s
                case "estimatedprintingtimenormalmode", "estimatedprintingtime" ->
                        estimatedSeconds = orKeep(estimatedSeconds, duration(value));
                // Cura writes metres, PrusaSlicer millimetres, and both call it "filament used".
                case "filamentused" -> filamentMillimetres = orKeep(filamentMillimetres, length(value));
                case "filamentusedmm" -> filamentMillimetres = orKeep(filamentMillimetres, decimal(value));
                case "filamentusedm" -> filamentMillimetres =
                        orKeep(filamentMillimetres, scale(decimal(value), 1000));
                case "layerheight", "layer_height" -> layerHeight = orKeep(layerHeight, decimal(value));
                default -> {
                    // A comment this host has no use for, which is almost all of them.
                }
            }
        }

        SliceInfo toSliceInfo() {
            return new SliceInfo(slicer, estimatedSeconds, filamentMillimetres, layerHeight);
        }
    }

    private static <T> T orKeep(T existing, T candidate) {
        return existing != null ? existing : candidate;
    }

    /**
     * Where the key ends: the first {@code :} or {@code =}, whichever comes first.
     *
     * <p>Both dialects are represented - Cura uses a colon, PrusaSlicer an equals - and a comment
     * with neither is prose rather than a key-value.
     */
    private static int separator(String text) {
        int colon = text.indexOf(':');
        int equals = text.indexOf('=');
        if (colon < 0) {
            return equals;
        }
        if (equals < 0) {
            return colon;
        }
        return Math.min(colon, equals);
    }

    /**
     * Lower-case letters and digits only.
     *
     * <p>So that {@code Layer height}, {@code layer_height} and {@code LAYER_HEIGHT} are one key,
     * and the bracketed units PrusaSlicer writes - {@code filament used [mm]} - fold into the key
     * rather than needing a case of their own.
     */
    private static String normalise(String key) {
        var sb = new StringBuilder(key.length());
        for (int i = 0; i < key.length(); i++) {
            char c = Character.toLowerCase(key.charAt(i));
            if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) {
                sb.append(c);
            }
        }
        return sb.toString();
    }

    /** The first two words, which is as much of "PrusaSlicer 2.6.0 on 2026-01-01" as names it. */
    private static String firstTwoWords(String text) {
        var parts = text.split("\\s+");
        if (parts.length <= 1) {
            return text;
        }
        return parts[0] + " " + parts[1];
    }

    /** A value with a unit suffix Cura writes inline: {@code 1.2345m} is metres. */
    private static BigDecimal length(String value) {
        if (value.endsWith("mm")) {
            return decimal(value.substring(0, value.length() - 2).trim());
        }
        if (value.endsWith("m")) {
            return scale(decimal(value.substring(0, value.length() - 1).trim()), 1000);
        }
        return decimal(value);
    }

    private static BigDecimal scale(BigDecimal value, int by) {
        return value == null ? null : value.multiply(BigDecimal.valueOf(by));
    }

    /**
     * {@code 2d 1h 2m 3s} as seconds, in any subset and any order.
     *
     * <p>Written out rather than matched, because the shape varies with the length of the print -
     * a ten-minute job has no hours in it - and a pattern that covered every subset would be less
     * readable than the loop.
     */
    private static Long duration(String value) {
        long total = 0;
        long current = 0;
        boolean sawDigit = false;
        boolean sawUnit = false;
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            if (c >= '0' && c <= '9') {
                current = current * 10 + (c - '0');
                sawDigit = true;
                continue;
            }
            int multiplier = switch (Character.toLowerCase(c)) {
                case 'd' -> 86400;
                case 'h' -> 3600;
                case 'm' -> 60;
                case 's' -> 1;
                default -> 0;
            };
            if (multiplier > 0 && sawDigit) {
                total += current * multiplier;
                current = 0;
                sawDigit = false;
                sawUnit = true;
            }
        }
        return sawUnit ? total : null;
    }

    private static Long wholeNumber(String value) {
        try {
            return Long.valueOf(value.trim());
        } catch (NumberFormatException notANumber) {
            return null;
        }
    }

    private static BigDecimal decimal(String value) {
        try {
            return new BigDecimal(value.trim());
        } catch (NumberFormatException notANumber) {
            return null;
        }
    }
}
