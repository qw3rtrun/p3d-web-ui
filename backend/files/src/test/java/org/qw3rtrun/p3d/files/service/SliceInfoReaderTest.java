package org.qw3rtrun.p3d.files.service;

import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * Reading a slicer's header, in the two dialects that matter.
 *
 * <p>The comments are found by {@code :gcode}'s tokenizer - that is plan item C1's third done-when
 * condition - and what is tested here is the half that is not G-code: Cura and PrusaSlicer each
 * invented their own keys, units and formats, and neither is in any specification.
 */
class SliceInfoReaderTest {

    private static byte[] bytes(String text) {
        return text.getBytes(StandardCharsets.UTF_8);
    }

    /** Cura: colons, seconds, and filament in metres. */
    @Test
    void itReadsACuraHeader() {
        var header = """
                ;FLAVOR:Marlin
                ;TIME:3661
                ;Filament used: 1.2345m
                ;Layer height: 0.2
                ;Generated with Cura_SteamEngine 5.2.1
                M104 S200
                """;

        var slice = SliceInfoReader.read(bytes(header));

        assertEquals("Cura_SteamEngine 5.2.1", slice.slicer());
        assertEquals(3661L, slice.estimatedSeconds());
        assertEquals(0, new BigDecimal("1234.5000").compareTo(slice.filamentMillimetres()),
                "1.2345m is 1234.5mm - Cura writes metres and the record keeps millimetres");
        assertEquals(0, new BigDecimal("0.2").compareTo(slice.layerHeight()));
    }

    /** PrusaSlicer: equals signs, a spelled-out duration, and filament already in millimetres. */
    @Test
    void itReadsAPrusaSlicerHeader() {
        var header = """
                ; generated by PrusaSlicer 2.6.0+win64 on 2026-01-01 at 12:00:00 UTC
                ; layer_height = 0.2
                M104 S200
                """;
        var footer = """
                ; filament used [mm] = 1234.5
                ; estimated printing time (normal mode) = 1h 2m 3s
                """;

        var slice = SliceInfoReader.read(bytes(header), bytes(footer));

        assertEquals("PrusaSlicer 2.6.0+win64", slice.slicer());
        assertEquals(3723L, slice.estimatedSeconds(), "1h 2m 3s");
        assertEquals(0, new BigDecimal("1234.5").compareTo(slice.filamentMillimetres()));
        assertEquals(0, new BigDecimal("0.2").compareTo(slice.layerHeight()));
    }

    /**
     * The tail window is read, which is the reason there are two.
     *
     * <p>PrusaSlicer writes its summary at the end of the file. A reader that only looked at the
     * top would find the slicer's name and nothing else, which is the least useful subset.
     */
    @Test
    void aValueOnlyInTheFooterIsStillFound() {
        var slice = SliceInfoReader.read(
                bytes("; generated by PrusaSlicer 2.6.0 on today\nG28\n"),
                bytes("; filament used [mm] = 99.5\n"));

        assertEquals(0, new BigDecimal("99.5").compareTo(slice.filamentMillimetres()));
    }

    /** The head window wins, so a value repeated at both ends is taken once and from the top. */
    @Test
    void theHeadWindowTakesPrecedenceOverTheTail() {
        var slice = SliceInfoReader.read(
                bytes("; layer_height = 0.2\n"),
                bytes("; layer_height = 0.3\n"));

        assertEquals(0, new BigDecimal("0.2").compareTo(slice.layerHeight()));
    }

    /** Durations come in whatever subset of units the print happens to need. */
    @Test
    void itReadsEveryShapeOfDuration() {
        assertEquals(45L, seconds("45s"));
        assertEquals(125L, seconds("2m 5s"));
        assertEquals(3723L, seconds("1h 2m 3s"));
        assertEquals(176523L, seconds("2d 1h 2m 3s"));
    }

    private static Long seconds(String duration) {
        return SliceInfoReader.read(bytes("; estimated printing time (normal mode) = " + duration + "\n"))
                .estimatedSeconds();
    }

    /**
     * A file from a slicer nothing here knows is a fact, not a failure.
     *
     * <p>It is still a perfectly printable file. Refusing it, or recording zeroes that would read
     * as "a print that takes no time and uses no filament", would both be worse answers than
     * nothing.
     */
    @Test
    void anUnrecognisedHeaderYieldsNothingRatherThanFailing() {
        var slice = SliceInfoReader.read(bytes(";SomeOtherSlicer v9\n;whatever: 12\nG28\n"));

        assertFalse(slice.isKnown());
        assertNull(slice.estimatedSeconds());
        assertNull(slice.layerHeight());
    }

    @Test
    void aFileWithNoCommentsAtAllYieldsNothing() {
        assertFalse(SliceInfoReader.read(bytes("G28\nG1 X10\n")).isKnown());
    }

    /** A value that is not a number is not taken, rather than becoming one. */
    @Test
    void aMalformedValueIsIgnored() {
        var slice = SliceInfoReader.read(bytes(";TIME:soon\n;Layer height: thin\n"));

        assertNull(slice.estimatedSeconds());
        assertNull(slice.layerHeight());
    }

    /**
     * A {@code ;} inside a parenthesised comment does not start a new one.
     *
     * <p>This is why the tokenizer does the finding. A reader that split lines on {@code ;} would
     * take {@code TIME:1} here as a key-value and report a one-second print.
     */
    @Test
    void aSemicolonInsideAnInlineCommentIsNotAComment() {
        var slice = SliceInfoReader.read(bytes("(a note ;TIME:1)\n;TIME:3600\n"));

        assertEquals(3600L, slice.estimatedSeconds());
    }
}
