    val all: List<GRq<*>> = decoders.map { it.decodeParams(emptyList()) }

    private val byHead: Map<GParameterWord<*>, GRqDecoder<*>> =
        decoders.groupBy { headKey(it.head()) }
            .mapValues { (_, claimants) -> claimants.first() }

    val ambiguousCodes: List<String> = listOf("G29", "G34", "M665", "M666")

    /**
     * The command [tokens] spell, head included, or null if no Marlin command has that head.
     *
     * Matching is on the head's number as written, so a non-canonical `M0105` does not
     * resolve - the lexeme is part of a number's identity in this model - but not on its
     * spacing, and not on its case (spec 2.2: `m104` is `M104`). The head is stripped with
     * `subList`, not `drop`: a view onto the tokens in hand, not a second copy of them.
     *
     * ```
     * MarlinCommands.decode(GTokenizer.parse("m104 S200").toList())   // SetHotendTemperature(M104 S200)
     * MarlinCommands.decode(GTokenizer.parse("M0105").toList())       // null
     * ```
     *
     * @param tokens one command's tokens, head included
     * @return the typed command, or null when no Marlin command has that head
     */
    fun decode(tokens: List<GToken>): GRq<*>? {
        val head = headWord(tokens) ?: return null
        val decoder = byHead[headKey(head)] ?: return null
        return decoder.decodeParams(tokens.subList(headEnd(tokens), tokens.size))
    }
}

/**
 * Named shortcuts for the commands this project sends most.
 *
 * Each is one line over the classes above and has no privileges they do not - the point is
 * a call site that reads as an intention rather than a code number. Each code-named
 * shortcut has an intention-named twin that returns the same command.
 *
 * ```
 * GEncoder.encode(MarlinG.tempReport(0).encode())   // M105 T0
 * ```
 *
 * Generated by `tools/marlin/gen_mcommands.py` from `doc/marlin-gcode/commands.json`,
 * extracted from MarlinFirmware/MarlinDocumentation at commit
 * `0856d12b0253378bc8d17a246fb09fc8c5437997`. Do not edit; regenerate.
 * How and why: `tools/marlin/README.md`, github.com/qw3rtrun/p3d-web-ui/issues/13.
 */
object MarlinG {

    /**
     * `M105 [T<index>]` - report temperatures.
     *
     * ```
     * GEncoder.encode(MarlinG.m105(0).encode())   // M105 T0
     * GEncoder.encode(MarlinG.m105().encode())    // M105
     * ```
     *
     * @param index the `T` tool index, or null for a bare `M105`
     * @return the command
     */
    fun m105(index: Int? = null): ReportHotendTemperature {
        return ReportHotendTemperature(index = index)
    }

    /**
     * [m105] by intention: report temperatures.
     *
     * ```
     * GEncoder.encode(MarlinG.tempReport(0).encode())   // M105 T0
     * ```
     *
     * @param tool the `T` tool index, or null for a bare `M105`
     * @return the command
     */
    fun tempReport(tool: Int? = null): ReportHotendTemperature {
        return m105(tool)
    }

    /**
     * `M115` - report firmware info and capabilities.
     *
     * ```
     * GEncoder.encode(MarlinG.m115().encode())   // M115
     * ```
     *
     * @return the command
     */
    fun m115(): FirmwareInfo {
        return FirmwareInfo()
    }

    /**
     * [m115] by intention: ask the firmware what it is.
     *
     * ```
     * GEncoder.encode(MarlinG.firmwareInfo().encode())   // M115
     * ```
     *
     * @return the command
     */
    fun firmwareInfo(): FirmwareInfo {
        return m115()
    }

    /**
     * `M155 [S<seconds>]` - temperature auto-report.
     *
     * ```
     * GEncoder.encode(MarlinG.m155(2).encode())   // M155 S2
     * ```
     *
     * @param period the `S` interval in seconds, or null for a bare `M155`
     * @return the command
     */
    fun m155(period: Int? = null): TemperatureAutoReport {
        return TemperatureAutoReport(seconds = period)
    }

    /**
     * [m155] by intention: have the firmware report temperatures on its own.
     *
     * ```
     * GEncoder.encode(MarlinG.autoReportTemp(2).encode())   // M155 S2
     * ```
     *
     * @param period the `S` interval in seconds, or null for a bare `M155`
     * @return the command
     */
    fun autoReportTemp(period: Int? = null): TemperatureAutoReport {
        return m155(period)
    }

    /**
     * `M104 T<tool> S<temp>`.
     *
     * The tool goes in `T` and not in `I`: M104 documents both, `I` being a material
     * preset index, and `T` is the one the old Java facade and `GSender.m104` send.
     *
     * ```
     * GEncoder.encode(MarlinG.m104(BigDecimal("200"), 0).encode())   // M104 S200 T0
     * ```
     *
     * @param temp the `S` target temperature
     * @param tool the `T` tool index, or null to leave it out
     * @return the command
     */
    fun m104(temp: BigDecimal, tool: Int? = null): SetHotendTemperature {
        return SetHotendTemperature(temp = temp, t = tool)
    }

    /**
     * [m104] by intention: set a hotend's target temperature, without waiting.
     *
     * ```
     * GEncoder.encode(MarlinG.setHotendTemperature(BigDecimal("200")).encode())   // M104 S200
     * ```
     *
     * @param temp the `S` target temperature
     * @param tool the `T` tool index, or null to leave it out
     * @return the command
     */
    fun setHotendTemperature(temp: BigDecimal, tool: Int? = null): SetHotendTemperature {
        return m104(temp, tool)
    }

    /**
     * `M140 S<temp>` - set the bed's target temperature.
     *
     * ```
     * GEncoder.encode(MarlinG.m140(BigDecimal("60")).encode())   // M140 S60
     * ```
     *
     * @param temp the `S` target temperature
     * @return the command
     */
    fun m140(temp: BigDecimal): SetBedTemperature {
        return SetBedTemperature(temp = temp)
    }

    /**
     * [m140] by intention: set the bed's target temperature, without waiting.
     *
     * ```
     * GEncoder.encode(MarlinG.setBedTemperature(BigDecimal("60")).encode())   // M140 S60
     * ```
     *
     * @param temp the `S` target temperature
     * @return the command
     */
    fun setBedTemperature(temp: BigDecimal): SetBedTemperature {
        return m140(temp)
    }
