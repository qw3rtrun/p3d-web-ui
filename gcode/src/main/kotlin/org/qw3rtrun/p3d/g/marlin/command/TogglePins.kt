/**
 * M43 T [S<pin>] [L<pin>] [I] [R<count>] [W<time>]
 *
 * Toggle Pins (debug).
 *
 * **`T` is fixed.** Every instance writes it; it is the base command's own
 * parameter and not a settable property of this variant, so it is absent
 * from the constructor rather than defaulted like the rest.
 *
 * Build one to send the command, and read one back with the companion's `decode`, which
 * is this command's [GRqDecoder]:
 *
 * ```
 * GEncoder.encode(TogglePins(pin = 1).encode())   // M43 T S1
 * TogglePins.decode(GTokenizer.parse("M43 T S1").toList())   // TogglePins(M43 T S1)
 * ```
 *
 * Generated by `tools/marlin/gen_mcommands.py` from `doc/marlin-gcode/commands.json`,
 * extracted from MarlinFirmware/MarlinDocumentation at commit
 * `0856d12b0253378bc8d17a246fb09fc8c5437997`. Do not edit; regenerate.
 * How and why: `tools/marlin/README.md`, github.com/qw3rtrun/p3d-web-ui/issues/13.
 *
 * @property pin `S` - pin
 * @property l `L` - pin
 * @property i `I`
 * @property count `R` - count
 * @property time `W` - time
 * @see <a href="https://marlinfw.org/docs/gcode/M43.html">MarlinFirmare M43 doc</a>
 */
data class TogglePins(
    val pin: Int? = null,
    val l: Int? = null,
    val i: Boolean = false,
    val count: Int? = null,
    val time: Int? = null,
) : GRq<TogglePins> {

    override fun encode(): GCommand {
        val words = ArrayList<GWord>(6)
        words.add(flag('T'))
        if (pin != null) words.add(word('S', pin))
        if (l != null) words.add(word('L', l))
        if (i) words.add(flag('I'))
        if (count != null) words.add(word('R', count))
        if (time != null) words.add(word('W', time))
        return M(43, *words.toTypedArray())
    }

    override fun toString(): String {
        return javaClass.simpleName + "(" + GEncoder.encode(encode()) + ')'
    }

    companion object : GRqDecoder<TogglePins> {

        override val letters: Set<Char> = setOf('I', 'L', 'R', 'S', 'W')

        override val bareString: Boolean = false

        override fun head(): GParameterWord<*> {
            return M(43).head
        }

        override fun decodeParams(tokens: List<GToken>): TogglePins {
            return TogglePins(
                pin = tokens.intOf('S'),
                l = tokens.intOf('L'),
                i = tokens.hasWord('I'),
                count = tokens.intOf('R'),
                time = tokens.intOf('W'),
            )
        }
    }
}
