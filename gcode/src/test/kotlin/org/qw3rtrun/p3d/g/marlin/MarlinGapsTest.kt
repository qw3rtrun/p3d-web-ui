/**
 * Where this module's transcription of Marlin's documentation is still thinner than the firmware,
 * as behaviour rather than as prose.
 *
 * The dotted quad is one of the gaps [#13](https://github.com/qw3rtrun/p3d-web-ui/issues/13) - the
 * issue titled *11 - The Marlin command set*, whose number and title do not match - lists,
 * described there from a reading that turned out to be off in a way that matters for what it would
 * take to close it. `M43 T`, the other gap #13 listed, is closed:
 * [#156](https://github.com/qw3rtrun/p3d-web-ui/issues/156) gave the pin-watch sub-mode its own
 * class, [TogglePins], and [PinWatchSubMode] below is what that fix looks like against the same
 * line the old, broken reading used. The remaining nested class is the one difference `M32` has
 * left now that [#37](https://github.com/qw3rtrun/p3d-web-ui/issues/37) has given it its filename
 * and [#114](https://github.com/qw3rtrun/p3d-web-ui/issues/114) has typed its `P`, and it is a
 * deliberate difference rather than a thin transcription. These tests say what the module actually
 * does today, so the next person starts from the behaviour and not from the description.
 *
 * Neither remaining gap is a **hand** fix: the classes involved are generated by
 * `tools/marlin/gen_mcommands.py` from `doc/marlin-gcode/commands.json`, which is itself generated,
 * and an edit to either is reverted by the next run. The fix is a change to the generator or to
 * `extract_marlin_docs.py`'s `CORRECTIONS` table (or, for `M43 T`, its `IRREGULAR_CODE_FOLDS`)
 * followed by a regeneration - #37 and #156 are the worked examples of doing exactly that.
 */
class MarlinGapsTest {

    private fun decode(gcode: String) =
        MarlinCommands.decode(GBlockReader.blocks(gcode).first().body)

    /**
     * **`M43 T` has a home: [TogglePins].**
     *
     * Before [#156](https://github.com/qw3rtrun/p3d-web-ui/issues/156), this line decoded to
     * [PinsDebugging], which models `T`, `S` and `W` as flags - so the sub-mode's values were read
     * as presence and thrown away, and `L` and `R` had no property to go in at all. `TogglePins`
     * models the sub-mode's own documented shape - `S`/`L`/`R`/`W` as the pin/count/delay values
     * M043-T.md gives them - and writes the `T` that selects it unconditionally, since `T` is
     * `M43`'s own parameter and not a settable property of the sub-mode.
     */
    @Nested
    inner class PinWatchSubMode {

        @Test
        fun `the sub-mode's class reads all four of its arguments`() {
            // `M43 T S<first pin> L<last pin> R<repeat> W<wait>` - the form M043-T.md documents.
            val watched = requireNotNull(
                TogglePins.decode(GBlockReader.blocks("M43 T S10 L20 R5 W100").first().body)
            )

            assertEquals(TogglePins(pin = 10, l = 20, count = 5, time = 100), watched)
            assertEquals(setOf('I', 'L', 'R', 'S', 'W'), TogglePins.letters)

            // `T` is not among the properties above and is still on the wire: it is fixed, not read.
            assertEquals("M43 T S10 L20 R5 W100", GEncoder.encode(watched.encode()))
        }

        @Test
        fun `the registry still answers the ordinary M43 for the shared head`() {
            // `M43` is one of MarlinCommands.ambiguousCodes now, same as G29 - the first-wins
            // tie-break keeps PinsDebugging, deliberately, because the ordinary M43 is the far
            // more common of the two and a bare lookup has no way to know which one a caller means.
            val probe = decode("M43 P1") as PinsDebugging

            assertEquals(1, probe.pin)
            assertEquals("M43 P1", GEncoder.encode(probe.encode()))
            assertEquals(true, "M43" in MarlinCommands.ambiguousCodes)
        }
    }

    /**
     * **`M32 cup.gco` is one ordinary print here and a subroutine call on the wire.**
     *
     * The parsing half of this is closed. Upstream's `M032.md` documents `M32 [P<value>]
     * [S<filepos>]` and no filename at all, and types `P` as carrying a value while writing it
     * bare in both of its own examples; `extract_marlin_docs.py`'s `CORRECTIONS` table now says
     * otherwise on both counts, so `M32 P !/models/lgbust.gco#` decodes to the flag and the name
     * and `M32 P` decodes to the flag alone - `MarlinDecoderTest` holds those.
     *
     * What is left is not a transcription gap but a deliberate difference of reading, pinned here
     * because it is the one that can print the wrong file. Marlin parses M32's line for parameters
     * *before* taking what is left as the filename - `M23` is in its string-argument special case
     * and `M32` is not - so a `p` anywhere in a name is also a bare `P`. `SdPrintProbe` sent
     * `M32 cup.gco` on 2026-11-10 and got
     * `echo:SUBROUTINE CALL target:"cup.gco" parent:"/LIVE.GCO" pos0` and two files printed, where
     * `M32 live.gco` got `echo:Now fresh file:` and one.
     *
     * This module will not read a letter back out of a bare string - that is what `beforeStringArg`
     * exists to prevent, and doing it is how a message comes back having quietly set a parameter
     * nobody wrote - so the difference stands and is reported rather than guessed away. It is also
     * why `/sd/print` sends `M23`+`M24` (#109) and why the three lines announcing the call are
     * typed (#111).
     */
    @Nested
    inner class SelectAndStartLetterInAName {

        @Test
        fun `a p inside the filename is text here and the flag there`() {
            val started = decode("M32 cup.gco") as SelectAndStart

            assertEquals(false, started.subroutineCall)
            assertEquals("cup.gco", started.filename)

            // Those same bytes answered `SUBROUTINE CALL`. The name is read right and the
            // behaviour is not what this decodes to - that is the whole of the pin.
            assertEquals("M32 cup.gco", GEncoder.encode(started.encode()))
        }

        @Test
        fun `the wrapping is carried, not interpreted`() {
            // `!` and `#` are a host's delimiters and are not stripped, so the wrapped form is
            // still exactly writable - deliberately, by putting them in the name.
            assertEquals(
                "M32 !/models/lgbust.gco#",
                GEncoder.encode(SelectAndStart(filename = "!/models/lgbust.gco#").encode()),
            )
            assertEquals(
                SelectAndStart(filename = "!/models/lgbust.gco#"),
                decode("M32 !/models/lgbust.gco#"),
            )
        }

        @Test
        fun `the form a host sends round-trips whole`() {
            // The transcript behind the correction: `>> N8 M32 test.gco*105` answered
            // `File opened: test.gco Size: 47`, `File selected`, `ok N8 P15 B3`.
            assertEquals(SelectAndStart(filename = "test.gco"), decode("M32 test.gco"))
            assertEquals(
                "M32 test.gco",
                GEncoder.encode(SelectAndStart(filename = "test.gco").encode()),
            )
        }
    }

    /**
     * **The dotted quad was never a spec 3.4a problem.**
     *
     * `MarlinDocExamplesTest` records it as waiting on bare rest-of-line strings, and
     * [#11](https://github.com/qw3rtrun/p3d-web-ui/issues/11) has since landed those - `M117`,
     * `M23` and the rest carry their arguments. `M552`/`M553`/`M554` still do not, because what they
     * need is not a rest-of-line string: `P192.168.1.55` is a **lettered** parameter whose value is
     * neither a number (spec 3.1 allows one `.`) nor a quoted string.
     *
     * The blocker is one layer lower than the issue says, and these pin where: the tokenizer makes
     * the quad a single `GUnknown`, and `GUnknown` is **not a `GValue`**, so no word can carry it
     * and `valueOf` cannot see it. Closing this means either widening the value model or giving the
     * generator an unquoted-string kind - a decision, not a transcription.
     *
     * [#158](https://github.com/qw3rtrun/p3d-web-ui/issues/158) spot-checked all three commands
     * against their own doc example lines (`M552 S-1 P192.168.1.55`, `M553 P255.255.255.192`,
     * `M554 P192.168.1.1` - the lines `marlin-doc-examples.txt` vendors) rather than `M553` alone:
     * `M552`'s `P` and `M554`'s `P` are typed `string` the same way `M553`'s is, so they share the
     * same gap and the same half-working round-trip, confirmed here rather than assumed from the
     * shared type. Neither carries a value `MarlinWords.stringArg`/`beforeStringArg` would help
     * with - the 23-command rest-of-line mechanism is not a third way to read a lettered parameter,
     * and inventing one here would be the wrong fix for a problem one layer lower.
     */
    @Nested
    inner class DottedQuad {

        @Test
        fun `the quad lexes to one token, and that token is not a value`() {
            val tokens = GTokenizer.parse("192.168.1.55").toList()

            assertEquals(1, tokens.size)
            assertEquals(GUnknown("192.168.1.55"), tokens[0])
            // Which is why no `GParameterWord` can hold it: a word's value is a GValue.
            assertEquals(false, tokens[0] is GValue)
        }

        @Test
        fun `so the form Marlin reads decodes to nothing`() {
            assertNull((decode("M552 S-1 P192.168.1.55") as EthernetIPAddressNetworkIF).ipAddress)
            assertNull((decode("M553 P255.255.255.192") as EthernetSubnetMask).subnetMask)
            assertNull((decode("M554 P192.168.1.1") as EthernetGatewayIPAddress).gateway)
        }

        @Test
        fun `and the form this module writes is not the form Marlin reads`() {
            // Upstream types `P` as a string, so the generator emits a quoted one, for all three.
            assertEquals(
                "M552 P\"192.168.1.55\" S-1",
                GEncoder.encode(EthernetIPAddressNetworkIF(ipAddress = "192.168.1.55", s = -1).encode()),
            )
            assertEquals(
                "M553 P\"255.255.255.192\"",
                GEncoder.encode(EthernetSubnetMask("255.255.255.192").encode()),
            )
            assertEquals(
                "M554 P\"192.168.1.1\"",
                GEncoder.encode(EthernetGatewayIPAddress("192.168.1.1").encode()),
            )
        }

        @Test
        fun `a quoted value does round-trip, which is the half that works`() {
            // Stated so the gap is not mistaken for "these three are broken": the classes are fine,
            // the wire form is the thing that does not match.
            val writtenIp = GEncoder.encode(EthernetIPAddressNetworkIF(ipAddress = "192.168.1.55", s = -1).encode())
            assertEquals(EthernetIPAddressNetworkIF(ipAddress = "192.168.1.55", s = -1), decode(writtenIp))

            val writtenMask = GEncoder.encode(EthernetSubnetMask("255.255.255.192").encode())
            assertEquals(EthernetSubnetMask("255.255.255.192"), decode(writtenMask))

            val writtenGateway = GEncoder.encode(EthernetGatewayIPAddress("192.168.1.1").encode())
            assertEquals(EthernetGatewayIPAddress("192.168.1.1"), decode(writtenGateway))
        }
    }
}
