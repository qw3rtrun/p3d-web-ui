package org.qw3rtrun.p3d.g.marlin

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNull
import org.junit.jupiter.api.Nested
import org.junit.jupiter.api.Test
import org.qw3rtrun.p3d.g.code.core.GEncoder
import org.qw3rtrun.p3d.g.code.core.block.GBlockReader
import org.qw3rtrun.p3d.g.code.core.token.GTokenizer
import org.qw3rtrun.p3d.g.code.core.token.GUnknown
import org.qw3rtrun.p3d.g.code.core.token.GValue
import org.qw3rtrun.p3d.g.marlin.command.EthernetSubnetMask
import org.qw3rtrun.p3d.g.marlin.command.PinsDebugging
import org.qw3rtrun.p3d.g.marlin.command.SelectAndStart

/**
 * Where this module's transcription of Marlin's documentation is still thinner than the firmware,
 * as behaviour rather than as prose.
 *
 * The first two are the gaps [#13](https://github.com/qw3rtrun/p3d-web-ui/issues/13) - the issue
 * titled *11 - The Marlin command set*, whose number and title do not match - lists. Both were
 * described there from a reading, and both readings are off in a way that matters for what it would
 * take to close them. The third is what [#37](https://github.com/qw3rtrun/p3d-web-ui/issues/37)
 * left behind after giving `M32` its filename. These tests say what the module actually does today,
 * so the next person starts from the behaviour and not from the description.
 *
 * None is fixed here, and a **hand** fix is impossible for all three: the classes involved are
 * generated by `tools/marlin/gen_mcommands.py` from `doc/marlin-gcode/commands.json`, which is
 * itself generated, and an edit to either is reverted by the next run. The fix is a change to the
 * generator or to `extract_marlin_docs.py`'s `CORRECTIONS` table followed by a regeneration - #37
 * is the worked example of doing exactly that.
 */
class MarlinGapsTest {

    private fun decode(gcode: String) =
        MarlinCommands.decode(GBlockReader.blocks(gcode).first().body)

    /**
     * **`M43 T` does have a home, and that is the problem.**
     *
     * The issue says the pin-watch sub-mode's parameters "cannot attach to `M43`" and asks whether
     * it deserves a hand-written class. What actually happens is narrower and worse than having no
     * home: the line decodes to [PinsDebugging], which models `T`, `S` and `W` as **flags** - so the
     * sub-mode's values are read as presence and thrown away, and `L` and `R` have nowhere to go at
     * all. Nothing reports a loss.
     */
    @Nested
    inner class PinWatchSubMode {

        @Test
        fun `the sub-mode decodes, and silently drops three of its four arguments`() {
            // `M43 T S<first pin> L<last pin> R<repeat> W<wait>` - the form M043-T.md documents.
            val watched = decode("M43 T S10 L20 R5 W100") as PinsDebugging

            // The mode letter survives, because it is a flag in both readings.
            assertEquals(true, watched.t)

            // `S` and `W` carry pin numbers here and are modelled as flags, so the numbers are gone.
            assertEquals(true, watched.s)
            assertEquals(true, watched.w)

            // `L` and `R` are not modelled at all - PinsDebugging has no property to put them in.
            assertEquals(setOf('E', 'I', 'P', 'S', 'T', 'W'), PinsDebugging.letters)

            // What goes back out is three bare flags: four arguments in, not one of their values
            // out. Note the order is the class's property order and not the line's - re-encoding a
            // command is canonical, not reproductive (`GEncoder.encode`), so `W` leads because it
            // is declared first.
            assertEquals("M43 W T S", GEncoder.encode(watched.encode()))
        }

        @Test
        fun `the ordinary M43 is unaffected, which is why this is easy to miss`() {
            val probe = decode("M43 P1") as PinsDebugging

            assertEquals(1, probe.pin)
            assertEquals("M43 P1", GEncoder.encode(probe.encode()))
        }
    }

    /**
     * **`M32 P !name#` reads `P !name#` as the whole filename.**
     *
     * The filename itself is modelled now: upstream's `M032.md` documents `M32 [P<value>]
     * [S<filepos>]` and no filename at all, and `extract_marlin_docs.py`'s `CORRECTIONS` table now
     * says otherwise, with the wire transcript that proves the plain form works. What is left is
     * one correction further on. `M032.md` types `P` as a parameter *with a value* and then sends
     * it bare in both of its own examples - #37 reports that the firmware reads it as a flag, which
     * is not checked here - so `P` is an `Int?`, a bare `P` cannot be a valued parameter, and
     * `stringArg` has nowhere to stop in front of it. The letter falls inside the name.
     *
     * Not fixed here because it is a *second* source correction - `P`'s kind, not M32's missing
     * string - and #37 does not ask for it. The plain `M32 <name>` form, which is what hosts send
     * and what #31's `SdWriteProbe` verified against the firmware, is unaffected.
     */
    @Nested
    inner class SelectAndStartWrappedFilename {

        @Test
        fun `the doc's own example reads its bare P as part of the filename`() {
            // `M32 P !/models/lgbust.gco#` - the form M032.md writes.
            val started = decode("M32 P !/models/lgbust.gco#") as SelectAndStart

            assertNull(started.p)
            assertEquals("P !/models/lgbust.gco#", started.filename)
        }

        @Test
        fun `a valued P is read, and the name after it is whole`() {
            // The same line with `P` spelled the way the page types it, `P<value>`: nothing is lost.
            val started = decode("M32 P1 !/models/lgbust.gco#") as SelectAndStart

            assertEquals(1, started.p)
            assertEquals("!/models/lgbust.gco#", started.filename)
        }

        @Test
        fun `the wrapping is carried, not interpreted`() {
            // `!` and `#` are a host's delimiters and are not stripped, so the wrapped form is
            // still exactly writable - deliberately, by putting them in the name.
            assertEquals(
                "M32 !/models/lgbust.gco#",
                GEncoder.encode(SelectAndStart(filename = "!/models/lgbust.gco#").encode()),
            )
            assertEquals(
                SelectAndStart(filename = "!/models/lgbust.gco#"),
                decode("M32 !/models/lgbust.gco#"),
            )
        }

        @Test
        fun `the form a host sends round-trips whole`() {
            // The transcript behind the correction: `>> N8 M32 test.gco*105` answered
            // `File opened: test.gco Size: 47`, `File selected`, `ok N8 P15 B3`.
            assertEquals(SelectAndStart(filename = "test.gco"), decode("M32 test.gco"))
            assertEquals(
                "M32 test.gco",
                GEncoder.encode(SelectAndStart(filename = "test.gco").encode()),
            )
        }
    }

    /**
     * **The dotted quad was never a spec 3.4a problem.**
     *
     * `MarlinDocExamplesTest` records it as waiting on bare rest-of-line strings, and
     * [#11](https://github.com/qw3rtrun/p3d-web-ui/issues/11) has since landed those - `M117`,
     * `M23` and the rest carry their arguments. `M552`/`M553`/`M554` still do not, because what they
     * need is not a rest-of-line string: `P192.168.1.55` is a **lettered** parameter whose value is
     * neither a number (spec 3.1 allows one `.`) nor a quoted string.
     *
     * The blocker is one layer lower than the issue says, and these pin where: the tokenizer makes
     * the quad a single `GUnknown`, and `GUnknown` is **not a `GValue`**, so no word can carry it
     * and `valueOf` cannot see it. Closing this means either widening the value model or giving the
     * generator an unquoted-string kind - a decision, not a transcription.
     */
    @Nested
    inner class DottedQuad {

        @Test
        fun `the quad lexes to one token, and that token is not a value`() {
            val tokens = GTokenizer.parse("192.168.1.55").toList()

            assertEquals(1, tokens.size)
            assertEquals(GUnknown("192.168.1.55"), tokens[0])
            // Which is why no `GParameterWord` can hold it: a word's value is a GValue.
            assertEquals(false, tokens[0] is GValue)
        }

        @Test
        fun `so the form Marlin reads decodes to nothing`() {
            assertNull((decode("M553 P255.255.255.192") as EthernetSubnetMask).subnetMask)
        }

        @Test
        fun `and the form this module writes is not the form Marlin reads`() {
            // Upstream types `P` as a string, so the generator emits a quoted one.
            assertEquals(
                "M553 P\"255.255.255.192\"",
                GEncoder.encode(EthernetSubnetMask("255.255.255.192").encode()),
            )
        }

        @Test
        fun `a quoted value does round-trip, which is the half that works`() {
            // Stated so the gap is not mistaken for "M553 is broken": the class is fine, the wire
            // form is the thing that does not match.
            val written = GEncoder.encode(EthernetSubnetMask("255.255.255.192").encode())

            assertEquals(EthernetSubnetMask("255.255.255.192"), decode(written))
        }
    }
}
